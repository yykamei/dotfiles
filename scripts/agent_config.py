"""Canonical agent configuration rendering and synchronization.

The rule files under `.config/opencode/rules/` and the skill directories under
`.config/opencode/skills/` are the source of truth. This module renders the
aggregate global instruction files used by Claude Code and Codex, links the
canonical skills into Claude Code's project directory, verifies both in
`--check` mode, and writes only when a check is not requested.

```python
from pathlib import Path
from agent_config import sync_rules, sync_skills

sync_rules(Path("/path/to/dotfiles"), check=False)
sync_skills(Path("/path/to/dotfiles"), check=False)
```
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import stat
import sys
import tempfile
from pathlib import Path

RULE_DIR = Path(".config/opencode/rules")
GENERATED_RULES = (Path(".claude/CLAUDE.md"), Path(".codex/AGENTS.md"))
SKILL_SOURCE = Path(".config/opencode/skills")
SKILL_DESTINATION = Path(".claude/skills")
SKILL_NAME = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
RULE_ORDER = (
    "core-philosophy.md",
    "code-comments.md",
    "commit-granularity.md",
    "git-startup.md",
    "plan-skill-rules.md",
    "design-gate.md",
    "plan-output-path.md",
    "plan-structure.md",
    "self-review.md",
    "software-design.md",
    "markdown-fence-safety.md",
    "question-batching.md",
    "language.md",
)
MAX_RULE_BYTES = 1_000_000
HEADER = """\
<!-- Generated by scripts/sync-agent-config.py from .config/opencode/rules/. Do not edit directly. -->
# Global Instructions

These are private global instructions for every project. The sections below are
**rules** — meta-principles that apply to every turn. Concrete step-by-step
workflows live in **skills** (loaded through the agent harness's skill
mechanism, or by reading the skill's `SKILL.md` directly).
"""
HEADING = re.compile(r"^#{1,6} ")
FENCE = re.compile(r"^\s*(`{3,}|~{3,})")


class ConfigError(RuntimeError):
    """Raised when the canonical configuration cannot be rendered or synced."""


def _display(root: Path, path: Path) -> str:
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)


def _check_components(root: Path, path: Path) -> None:
    try:
        resolved = path.resolve(strict=False)
        resolved_root = root.resolve()
    except (OSError, RuntimeError) as error:
        detail = getattr(error, "strerror", None) or "symlink loop"
        raise ConfigError(f"cannot resolve {_display(root, path)}: {detail}") from error
    if not resolved.is_relative_to(resolved_root):
        raise ConfigError(f"path escapes the repository: {_display(root, path)}")

    current = path
    while current != root:
        if current.is_symlink():
            raise ConfigError(f"refusing symlinked path: {_display(root, current)}")
        if current.parent == current:
            break
        current = current.parent


def _lstat_mode(root: Path, path: Path) -> int | None:
    try:
        return path.lstat().st_mode
    except FileNotFoundError:
        return None
    except OSError as error:
        raise ConfigError(
            f"cannot inspect {_display(root, path)}: {error.strerror or error}"
        ) from error


def _check_path(root: Path, path: Path) -> None:
    """Reject symlinked or non-regular files and paths outside the repository."""
    _check_components(root, path)
    mode = _lstat_mode(root, path)
    if mode is not None and not stat.S_ISREG(mode):
        raise ConfigError(f"refusing non-regular path: {_display(root, path)}")


def _check_directory(root: Path, path: Path) -> None:
    """Reject symlinked or non-directory paths and paths outside the repository."""
    _check_components(root, path)
    mode = _lstat_mode(root, path)
    if mode is not None and not stat.S_ISDIR(mode):
        raise ConfigError(f"refusing non-directory path: {_display(root, path)}")


def _validate_rule_set(root: Path) -> None:
    directory = root / RULE_DIR
    if not directory.is_dir():
        raise ConfigError(f"missing rule directory: {_display(root, directory)}")

    present = {path.name for path in directory.glob("*.md")}
    expected = set(RULE_ORDER)
    if present == expected:
        return

    details = []
    missing = sorted(expected - present)
    extra = sorted(present - expected)
    if missing:
        details.append("missing: " + ", ".join(missing))
    if extra:
        details.append("unexpected: " + ", ".join(extra))
    raise ConfigError("rule set mismatch (" + "; ".join(details) + ")")


def _read_rule(root: Path, name: str) -> str:
    path = root / RULE_DIR / name
    _check_path(root, path)
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(path, flags)
    except OSError as error:
        raise ConfigError(
            f"cannot read rule {_display(root, path)}: {error.strerror or error}"
        ) from error

    with os.fdopen(descriptor, "rb") as handle:
        if not stat.S_ISREG(os.fstat(handle.fileno()).st_mode):
            raise ConfigError(f"not a regular file: {_display(root, path)}")
        data = handle.read(MAX_RULE_BYTES + 1)

    if len(data) > MAX_RULE_BYTES:
        raise ConfigError(f"rule is too large: {_display(root, path)}")
    try:
        return data.decode("utf-8").removeprefix("\ufeff")
    except UnicodeDecodeError as error:
        raise ConfigError(f"rule is not UTF-8: {_display(root, path)}") from error


def demote_headings(text: str) -> str:
    """Demote Markdown headings by one level, leaving fenced code untouched."""
    lines = []
    fence = None
    for line in text.splitlines():
        match = FENCE.match(line)
        if fence is None:
            if match:
                marker = match.group(1)
                fence = (marker[0], len(marker))
            elif HEADING.match(line):
                if line.startswith("###### "):
                    raise ConfigError("level-6 heading cannot be demoted")
                line = "#" + line
        elif match:
            marker = match.group(1)
            if (
                marker[0] == fence[0]
                and len(marker) >= fence[1]
                and not line.strip()[len(marker):].strip()
            ):
                fence = None
        lines.append(line)

    if fence is not None:
        raise ConfigError("unterminated fenced code block")
    return "\n".join(lines)


def render_rules(root: Path) -> str:
    """Render the aggregate global instructions from the canonical rules."""
    _validate_rule_set(root)
    sections = []
    for name in RULE_ORDER:
        text = _read_rule(root, name).strip()
        try:
            sections.append(demote_headings(text))
        except ConfigError as error:
            raise ConfigError(f"{name}: {error}") from error
    return HEADER + "\n" + "\n\n".join(sections) + "\n"


def _check_skill_tree(root: Path, skill: Path) -> None:
    def onerror(error: OSError) -> None:
        filename = getattr(error, "filename", None)
        if filename is None:
            raise ConfigError(
                f"cannot inspect skill tree: {error.strerror or error}"
            ) from error
        raise ConfigError(
            f"cannot inspect {_display(root, Path(filename))}: "
            f"{error.strerror or error}"
        ) from error

    for directory, dirnames, filenames in os.walk(
        skill, followlinks=False, onerror=onerror
    ):
        for name in dirnames + filenames:
            path = Path(directory) / name
            if path.is_symlink():
                raise ConfigError(f"refusing symlinked path: {_display(root, path)}")
            if name in dirnames:
                _check_directory(root, path)
            else:
                _check_path(root, path)


def _skill_directories(root: Path) -> list[Path]:
    source = root / SKILL_SOURCE
    _check_directory(root, source)
    if not source.is_dir():
        raise ConfigError(f"skill source is not a directory: {_display(root, source)}")

    directories = []
    for path in sorted(source.iterdir()):
        if path.is_symlink():
            raise ConfigError(f"refusing symlinked path: {_display(root, path)}")
        if not SKILL_NAME.fullmatch(path.name):
            if path.is_dir():
                raise ConfigError(f"invalid skill directory name: {path.name}")
            continue
        if not path.is_dir():
            raise ConfigError(f"skill path is not a directory: {_display(root, path)}")
        _check_directory(root, path)
        if not (path / "SKILL.md").is_file():
            raise ConfigError(f"skill is missing SKILL.md: {_display(root, path)}")
        _check_skill_tree(root, path)
        directories.append(path)
    return directories


def _current_link(link: Path, source: Path) -> bool:
    if not link.is_symlink():
        return False
    try:
        target = os.readlink(link)
    except OSError as error:
        raise ConfigError(
            f"cannot read link {link.name}: {error.strerror or error}"
        ) from error
    return target == os.path.relpath(source, link.parent)


def sync_skills(root: Path, *, check: bool) -> list[str]:
    """Mirror the canonical skills as symlinks in Claude Code's directory.

    Returns the repository-relative links that are missing, stale, or point
    somewhere else. With `check=True`, nothing is written.
    """
    destination = root / SKILL_DESTINATION
    skills = _skill_directories(root)
    _check_directory(root, destination)
    expected_names = {path.name for path in skills}

    for source in skills:
        link = destination / source.name
        if link.is_symlink() or not link.exists():
            continue
        if not link.is_dir() or not (link / "SKILL.md").is_file():
            raise ConfigError(f"refusing non-skill path: {_display(root, link)}")

    changed = []
    if destination.is_dir():
        for path in sorted(destination.iterdir()):
            if path.name in expected_names:
                continue
            changed.append(str(path.relative_to(root)))
            if check:
                continue
            if path.is_symlink():
                path.unlink()
            elif path.is_dir():
                _check_directory(root, path)
                shutil.rmtree(path)
            else:
                path.unlink()

    for source in skills:
        link = destination / source.name
        if _current_link(link, source):
            continue
        if link.is_symlink():
            changed.append(str(link.relative_to(root)))
            if not check:
                link.unlink()
        elif link.exists():
            if not link.is_dir() or not (link / "SKILL.md").is_file():
                raise ConfigError(f"refusing non-skill path: {_display(root, link)}")
            changed.append(str(link.relative_to(root)))
            if not check:
                _check_directory(root, link)
                shutil.rmtree(link)
        else:
            changed.append(str(link.relative_to(root)))

        if check:
            continue
        destination.mkdir(parents=True, exist_ok=True)
        _check_directory(root, destination)
        link.symlink_to(os.path.relpath(source, destination), target_is_directory=True)
    return changed


def _write_atomic(path: Path, data: bytes) -> None:
    try:
        mode = path.lstat().st_mode & 0o777
    except FileNotFoundError:
        mode = 0o644
    except OSError as error:
        raise ConfigError(
            f"cannot inspect {path.name}: {error.strerror or error}"
        ) from error

    try:
        descriptor, temporary = tempfile.mkstemp(
            dir=path.parent, prefix=f".{path.name}.", suffix=".tmp"
        )
    except OSError as error:
        raise ConfigError(
            f"cannot create temporary file for {path.name}: "
            f"{error.strerror or error}"
        ) from error

    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(data)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    except OSError as error:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise ConfigError(
            f"cannot write {path.name}: {error.strerror or error}"
        ) from error
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def sync_rules(root: Path, *, check: bool) -> list[str]:
    """Write or verify the aggregate rule files.

    Returns the repository-relative paths that are missing or out of date.
    With `check=True`, nothing is written.
    """
    expected = render_rules(root).encode("utf-8")
    changed = []
    for relative in GENERATED_RULES:
        path = root / relative
        _check_path(root, path)
        try:
            current = path.read_bytes()
        except FileNotFoundError:
            current = None
        except OSError as error:
            raise ConfigError(
                f"cannot read {_display(root, path)}: {error.strerror or error}"
            ) from error

        if current == expected:
            continue
        changed.append(str(relative))
        if check:
            continue

        try:
            path.parent.mkdir(parents=True, exist_ok=True)
        except OSError as error:
            raise ConfigError(
                f"cannot create {_display(root, path.parent)}: "
                f"{error.strerror or error}"
            ) from error
        _check_path(root, path)
        _write_atomic(path, expected)
    return changed


def main(argv: list[str] | None = None, *, root: Path | None = None) -> int:
    """CLI entry point for sync-agent-config.py."""
    parser = argparse.ArgumentParser(
        description=(
            "Render and check the Claude Code and Codex global rules and "
            "skill links."
        )
    )
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args(argv)
    target = root if root is not None else Path(__file__).resolve().parents[1]
    try:
        if args.check:
            changed = sync_rules(target, check=True)
            changed += sync_skills(target, check=True)
        else:
            sync_rules(target, check=True)
            sync_skills(target, check=True)
            changed = sync_rules(target, check=False)
            changed += sync_skills(target, check=False)
    except (ConfigError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    if args.check:
        for relative in changed:
            print(f"out of date: {relative}", file=sys.stderr)
        return 1 if changed else 0
    for relative in changed:
        print(f"updated: {relative}")
    return 0
